const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const store = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../mail-store.js'), 'utf8'), store);
const fixtures = vm.createContext({Store: store});
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname, 'fixtures/mailbox-responses.js'), 'utf8').replace(/^\.import[^\n]*\n/gm, ''), fixtures);
const row = (id, folder = 'Inbox') => Object.assign(
    store.message(id, 'Sender', 'Subject', 'Body', 'Work', 'Today', '12:00', false), {folder});
let state = store.emptyMailbox();
const inbox = row('inbox');
const archived = row('archived', 'Archive');
const retained = row('retained', 'Spam');
state = fixtures.replaceMailboxRows(state, [inbox]);
state = store.replaceSearchRows(state, [inbox, archived], 'needle');
state = store.upsertMessages(state, [retained]);
state.search = Object.assign({}, state.search, {selectedId: retained.id});
let views = store.messageViews(state);
assert.deepEqual(Array.from(views.mailbox.ids), ['inbox']);
assert.deepEqual(Array.from(views.search.ids), ['inbox', 'archived']);
assert.equal(Object.keys(views.records).length, 3);
assert.equal(views.records.inbox, inbox);
assert.equal(store.find(state, 'archived'), archived);
assert.equal(store.find(state, 'retained'), retained);
assert.equal(store.find(state, 'missing'), null);
// Navigation reuses the index and both membership lists, without serializing records.
const searching = store.reduce(state, 'search', {text: 'needle'});
assert.equal(store.messageViews(searching), views);
assert.equal(store.find(searching, 'inbox'), inbox);
const selected = store.reduce(searching, 'select', {id: archived.id});
const closed = store.reduce(selected, 'closeSearch');
assert.equal(store.find(closed, archived.id), archived);
assert.equal(store.find(state, archived.id), archived);
assert.deepEqual(Array.from(store.messageViews(closed).mailbox.ids), ['inbox', 'archived']);
// Replacement responses do not change earlier state or the other view's membership.
const refreshedInbox = Object.assign({}, inbox, {subject: 'Updated subject'});
const refreshed = fixtures.replaceMailboxRows(state, [refreshedInbox]);
assert.equal(store.find(refreshed, inbox.id), refreshedInbox);
assert.equal(store.find(state, inbox.id), inbox);
assert.equal(store.messageViews(refreshed).search.ids, views.search.ids);
const nextSearch = store.replaceSearchRows(Object.assign({}, refreshed, {ui: Object.assign({}, refreshed.ui, {selected: archived.id})}), [], 'other');
assert.equal(store.find(nextSearch, archived.id), archived);
assert.equal(store.find(nextSearch, retained.id), null);
assert.equal(store.messageViews(nextSearch).mailbox.ids, store.messageViews(refreshed).mailbox.ids);
// A folder refresh updates the same record already referenced by a search result.
const duplicate = Object.assign({}, archived, {subject: 'Search snapshot'});
const precedence = fixtures.replaceMailboxRows(store.replaceSearchRows(store.emptyMailbox(), [duplicate], 'duplicate'), [archived]);
assert.equal(store.find(precedence, archived.id), archived);
assert.equal(store.messageViews(precedence).search.rows[0], archived);
assert.equal(store.messageViews(precedence).mailbox.rows[0], archived);
const moved = store.reduce(Object.assign({}, state, {ui: Object.assign({}, state.ui, {selected: inbox.id})}), 'move', {folder: 'Archive'});
assert.equal(store.find(moved, inbox.id).folder, 'Archive');
assert.equal(store.find(state, inbox.id).folder, 'Inbox');
const undone = store.reduce(moved, 'undo');
assert.equal(store.find(undone, inbox.id).folder, 'Inbox');
const unread = store.reduce(Object.assign({}, state, {ui: Object.assign({}, state.ui, {selected: inbox.id})}), 'unread', {value: true});
assert.equal(store.find(unread, inbox.id).unread, true);
assert.equal(store.find(state, inbox.id).unread, false);
console.log('Message views: shared ID lookup, independent membership, navigation identity and mutation/Undo passed');
