const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const path = require('node:path');
const store = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../mail-store.js'), 'utf8'), store);
const fixtures = vm.createContext({Store: store});
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname, 'fixtures/mailbox-responses.js'), 'utf8').replace(/^\.import[^\n]*\n/gm, ''), fixtures);
const make = (id, folder = 'Inbox') => Object.assign(
    store.message(id, 'Sender', 'Subject', 'Body', 'Work', 'Today', '12:00', false), {folder});
let state = fixtures.replaceMailboxRows(store.emptyMailbox(), [make('shared'), make('unrelated')]);
state.ui.selected = 'shared';
state = store.replaceSearchRows(state, [store.find(state, 'shared'), make('outside', 'Archive')], 'needle');
assert.equal(Object.hasOwn(state, 'messages'), false);
assert.equal(Object.hasOwn(state.search, 'messages'), false);
assert.equal(Object.hasOwn(state.search, 'selected'), false);
assert.deepEqual(Array.from(state.mailboxIds), ['shared', 'unrelated']);
assert.deepEqual(Array.from(state.search.ids), ['shared', 'outside']);
assert.equal(Object.keys(state.records).length, 3);
const fail = () => { throw new Error('Flag updates must not serialize message records'); };
Object.defineProperty(state.records, 'toJSON', {value: fail, configurable: true});
const unread = store.reduce(state, 'unread', {value: true});
assert.notEqual(unread.records, state.records);
assert.equal(store.find(unread, 'shared').unread, true);
assert.equal(store.find(state, 'shared').unread, false);
assert.equal(store.find(unread, 'unrelated'), store.find(state, 'unrelated'));
assert.equal(unread.mailboxIds, state.mailboxIds);
assert.equal(unread.search.ids, state.search.ids);
const starred = store.reduce(unread, 'star');
assert.equal(store.find(starred, 'shared').starred, true);
assert.equal(store.mailboxMessages(starred)[0], store.searchMessages(starred)[0]);
assert.equal(starred.mailboxIds, state.mailboxIds);
assert.equal(starred.search.ids, state.search.ids);
const selected = store.reduce(store.reduce(starred, 'search', {text: 'needle'}), 'select', {id: 'shared'});
assert.equal(store.find(selected, 'shared').unread, false);
assert.equal(store.mailboxMessages(selected)[0], store.searchMessages(selected)[0]);
assert.equal(store.find(selected, 'unrelated'), store.find(state, 'unrelated'));
delete state.records.toJSON;
const freshServerRow = Object.assign({}, store.find(state, 'shared'), {subject: 'Updated server subject'});
const refreshedSearch = store.replaceSearchRows(state, [freshServerRow], 'needle');
assert.equal(store.find(refreshedSearch, 'shared'), freshServerRow);
assert.equal(store.mailboxMessages(refreshedSearch)[0], freshServerRow);
assert.equal(store.searchMessages(refreshedSearch)[0], freshServerRow);
assert.equal(store.find(state, 'shared').subject, 'Subject');
// A new search releases obsolete search-only records but retains the open message by ID.
let outside = store.reduce(store.reduce(state, 'search', {text: 'needle'}), 'select', {id: 'outside'});
outside = store.replaceSearchRows(outside, [make('fresh', 'Spam')], 'fresh');
assert.equal(outside.search.selectedId, 'outside');
assert.equal(store.current(outside).id, 'outside');
outside = store.reduce(outside, 'select', {id: 'shared'});
outside = store.replaceSearchRows(outside, [], 'empty');
assert.equal(store.find(outside, 'outside'), null);
assert.equal(store.find(outside, 'fresh'), null);
assert.equal(Object.keys(outside.records).length, 2);
// Deleted folder rows cannot survive through an unreferenced record.
let removed = store.replaceBackendView(state, [], store.backendViewKey('Inbox', '', 'All mail', 'Newest first'));
assert.equal(store.find(removed, 'unrelated'), null);
assert.equal(store.find(removed, 'shared').id, 'shared'); // Explicit retained search selection.
removed = store.removeMessages(removed, ['shared']);
assert.equal(store.find(removed, 'shared'), null);
assert.equal(removed.search.ids.includes('shared'), false);
assert.equal(removed.search.selectedId, '');
const onlyFolder = fixtures.replaceMailboxRows(store.emptyMailbox(), [make('only')]);
assert.equal(store.find(store.replaceBackendView(onlyFolder, [], store.backendViewKey('Inbox', '', 'All mail', 'Newest first')), 'only'), null);
// Undo restores shared data and both memberships without creating view-specific copies.
const moved = store.reduce(state, 'move', {folder: 'Archive'});
assert.equal(store.find(moved, 'shared').folder, 'Archive');
assert.equal(store.find(state, 'shared').folder, 'Inbox');
const undone = store.reduce(moved, 'undo');
assert.equal(store.find(undone, 'shared').folder, 'Inbox');
assert.equal(store.mailboxMessages(undone)[0], store.searchMessages(undone)[0]);
assert.deepEqual(Array.from(undone.mailboxIds), Array.from(state.mailboxIds));
assert.deepEqual(Array.from(undone.search.ids), Array.from(state.search.ids));
const changedSearch = store.replaceSearchRows(moved, [make('new-search-result', 'Spam')], 'later');
const undoneAfterSearch = store.reduce(changedSearch, 'undo');
assert.equal(undoneAfterSearch.search.query, 'later');
assert.deepEqual(Array.from(undoneAfterSearch.search.ids), ['new-search-result']);
assert.equal(store.find(undoneAfterSearch, 'new-search-result').id, 'new-search-result');
assert.equal(store.find(undoneAfterSearch, 'shared').folder, 'Inbox');
const permanentlyRemoved = store.removeMessages(moved, ['shared'], true);
assert.equal(permanentlyRemoved.ui.undo, null);
assert.equal(store.find(permanentlyRemoved, 'shared'), null);
const removedUnrelated = store.removeMessages(moved, ['unrelated'], true);
const undoAfterPermanentDelete = store.reduce(removedUnrelated, 'undo');
assert.equal(store.find(undoAfterPermanentDelete, 'unrelated'), null);
assert.equal(undoAfterPermanentDelete.mailboxIds.includes('unrelated'), false);
assert.equal(store.find(undoAfterPermanentDelete, 'shared').folder, 'Inbox');
const duplicate = fixtures.replaceMailboxRows(store.emptyMailbox(), [make('same'), make('same')]);
assert.equal(duplicate.mailboxIds.length, 1);
assert.equal(Object.keys(duplicate.records).length, 1);
console.log('Normalized store: one record per ID, shared flags without serialization, pruning, deletion and Undo passed');
