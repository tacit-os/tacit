const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname, '../mail-store.js'), 'utf8'), context);
const fixtures = vm.createContext({Store: context});
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname, 'fixtures/mailbox-responses.js'), 'utf8').replace(/^\.import[^\n]*\n/gm, ''), fixtures);
let state = context.emptyMailbox();
const normal = context.message('normal', 'Sender', 'Inbox', 'Body', 'Work', 'Today', '12:00', false);
state = fixtures.replaceMailboxRows(state, [normal]);
Object.defineProperty(state.mailboxIds, "toJSON", {value() { throw new Error("Navigation must retain message arrays without serialization"); }});
const hit = Object.assign({}, normal, {id:'found', folder:'Archive', backendAccount:'work', backendConversation:'found-thread'});
state = context.replaceSearchRows(state, [hit], 'needle');
Object.defineProperty(state, 'toJSON', {value() { throw new Error('Navigation must not serialize the mailbox'); }});
let searching = context.reduce(state, 'search', {text:'needle'});
assert.equal(searching.mailboxIds, state.mailboxIds);
assert.equal(searching.search, state.search);
assert.equal(context.results(searching)[0], hit);
let selected = context.reduce(searching, 'select', {id:hit.id});
let closed = context.reduce(selected, 'closeSearch');
assert.equal(closed.ui.selected, hit.id);
assert.equal(closed.ui.folder, 'Archive');
assert.equal(closed.search, selected.search);
assert.equal(closed.search.ids, state.search.ids);
assert.equal(context.mailboxMessages(closed)[0], normal);
assert.equal(context.current(closed), hit);
assert.equal(context.results(closed)[0].id, hit.id);
assert.equal(state.ui.searching, false);
console.log('Search slice: state identity, selection and serialization checks passed');

const changedResults = context.replaceSearchRows(selected, [], 'different');
assert.equal(context.current(changedResults), hit);
assert.equal(context.current(context.reduce(changedResults, 'closeSearch')), hit);
